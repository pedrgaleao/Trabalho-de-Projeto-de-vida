create table if not exists public.items (
  id bigint generated by default as identity primary key,
  name text not null,
  category text not null,
  location text not null,
  description text default '',
  photo_url text not null,
  status text not null default 'disponivel'
    check (status in ('disponivel', 'devolvido')),
  created_at timestamptz not null default now()
);

alter table public.items enable row level security;

drop policy if exists "Public can view items" on public.items;
create policy "Public can view items"
on public.items for select
to anon, authenticated
using (true);

drop policy if exists "Public can add items" on public.items;
create policy "Public can add items"
on public.items for insert
to anon, authenticated
with check (
  char_length(name) between 1 and 80
  and char_length(location) between 1 and 120
  and char_length(coalesce(description, '')) <= 500
  and status = 'disponivel'
);

drop policy if exists "Public can mark items returned" on public.items;
create policy "Public can mark items returned"
on public.items for update
to anon, authenticated
using (status = 'disponivel')
with check (status = 'devolvido');

-- Bucket público para as fotos dos objetos.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('fotos-objetos', 'fotos-objetos', true, 5242880, array['image/jpeg','image/png','image/webp'])
on conflict (id) do update
set public = true, file_size_limit = 5242880,
    allowed_mime_types = array['image/jpeg','image/png','image/webp'];

drop policy if exists "Public can upload item photos" on storage.objects;
create policy "Public can upload item photos"
on storage.objects for insert
to anon, authenticated
with check (bucket_id = 'fotos-objetos');

drop policy if exists "Public can view item photos" on storage.objects;
create policy "Public can view item photos"
on storage.objects for select
to anon, authenticated
using (bucket_id = 'fotos-objetos');

drop policy if exists "Public can delete own item photos" on storage.objects;
create policy "Public can delete own item photos"
on storage.objects for delete
to anon, authenticated
using (bucket_id = 'fotos-objetos');
